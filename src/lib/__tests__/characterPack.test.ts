// ============ detectFormat 测试 ============

describe('detectFormat', () => {
  it('should detect pack-config format by spritePath', () => {
    const fmt = detectFormat(makePackConfig())
    expect(fmt).toBe('pack-config')
  })

  it('should detect resource-package format by meta + sprites', () => {
    const fmt = detectFormat(makeResourcePackage())
    expect(fmt).toBe('resource-package')
  })

  it('should detect pet-metadata format by formatVersion + sprite', () => {
    const fmt = detectFormat(makePetMetadata())
    expect(fmt).toBe('pet-metadata')
  })

  it('should detect pet-metadata by atlas + sprite without formatVersion', () => {
    const fmt = detectFormat({ sprite: 'sheet.webp', atlas: { cellW: 128, cellH: 128, cols: 8, rows: 9 } })
    expect(fmt).toBe('pet-metadata')
  })

  it('should return unknown for unrecognized format', () => {
    const fmt = detectFormat({ foo: 'bar' })
    expect(fmt).toBe('unknown')
  })

  it('should prioritize resource-package when both meta and spritePath exist', () => {
    // meta takes precedence
    const fmt = detectFormat({ ...makePackConfig(), meta: { id: 'x' } })
    expect(fmt).toBe('resource-package')
  })
})

// ============ parseCharacterPack: CharacterPackConfig 格式 ============

describe('parseCharacterPack: CharacterPackConfig 格式', () => {
  it('should parse all fields correctly', () => {
    const result = parseCharacterPack(makePackConfig())

    expect(result.ok).toBe(true)
    expect(result.profile).not.toBeNull()
    expect(result.profile!.id).toBe('test-cat')
    expect(result.profile!.name).toBe('Test Cat')
    expect(result.profile!.displayName).toBe('Test Cat')
    expect(result.profile!.spriteAsset).toBe('/pets/test-cat/spritesheet.webp')
    expect(result.profile!.spriteType).toBe('atlas')
    expect(result.profile!.atlasLayout).toEqual({ cellW: 192, cellH: 208, cols: 8, rows: 9 })
    expect(result.profile!.themeColor).toEqual({ primary: '#ff6b6b', secondary: '#4ecdc4' })
    expect(result.profile!.source).toBe('TestAuthor')
    expect(result.profile!.birthBackground).toBe('A test cat character')
    expect(result.profile!.type).toBe('community')
  })

  it('should use ATLAS defaults when atlasLayout is missing', () => {
    const result = parseCharacterPack(makePackConfig({ atlasLayout: undefined }))
    expect(result.ok).toBe(true)
    expect(result.profile!.atlasLayout).toEqual({ cellW: ATLAS.cellW, cellH: ATLAS.cellH, cols: ATLAS.cols, rows: ATLAS.rows })
  })

  it('should use author as source when tags is missing', () => {
    const result = parseCharacterPack(makePackConfig({ author: 'CustomAuthor', tags: undefined }))
    expect(result.profile!.source).toBe('CustomAuthor')
  })

  it('should fail when id is missing', () => {
    const result = parseCharacterPack(makePackConfig({ id: undefined }))
    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
    expect(result.messages.some((m) => m.level === 'error' && m.field === 'id')).toBe(true)
  })

  it('should auto-set chromaKey for video spriteType', () => {
    const result = parseCharacterPack(makePackConfig({ spriteType: 'video' }))
    expect(result.ok).toBe(true)
    expect(result.profile!.chromaKey).toBe('auto')
    expect(result.messages.some((m) => m.level === 'info' && m.message.includes('chromaKey'))).toBe(true)
  })
})

// ============ parseCharacterPack: CharacterResourcePackage 格式 ============

describe('parseCharacterPack: CharacterResourcePackage 格式', () => {
  it('should parse all fields correctly', () => {
    const result = parseCharacterPack(makeResourcePackage())

    expect(result.ok).toBe(true)
    expect(result.profile).not.toBeNull()
    expect(result.profile!.id).toBe('test-dog')
    expect(result.profile!.name).toBe('test-dog')
    expect(result.profile!.displayName).toBe('Test Dog')
    expect(result.profile!.spriteAsset).toBe('/pets/test-dog/spritesheet.png')
    expect(result.profile!.spriteType).toBe('atlas')
    expect(result.profile!.personality).toEqual({ warmth: 0.7, liveliness: 0.3, dependence: 0.5, directness: -0.2, rationality: 0.1 })
    expect(result.profile!.signaturePhrase).toBe('汪汪！')
    expect(result.profile!.classicQuotes).toEqual(['我是一只狗'])
    expect(result.profile!.bubbleMessages.idle).toEqual(['汪...'])
    expect(result.profile!.bubbleMessages.hungry).toEqual(['饿饿了'])
    expect(result.profile!.source).toBe('Community')
    expect(result.profile!.type).toBe('community')
  })

  it('should use target atlas when isShimeji is true', () => {
    const pkg = makeResourcePackage()
    ;(pkg.sprites as Record<string, unknown>[])[0]!.isShimeji = true
    const result = parseCharacterPack(pkg)

    expect(result.ok).toBe(true)
    expect(result.profile!.atlasLayout).toEqual({ cellW: 192, cellH: 208, cols: 8, rows: 9 })
  })

  it('should normalize webp/png spriteType to atlas', () => {
    const pkg = makeResourcePackage()
    ;(pkg.sprites as Record<string, unknown>[])[0]!.type = 'webp'
    const result = parseCharacterPack(pkg)

    expect(result.ok).toBe(true)
    expect(result.profile!.spriteType).toBe('atlas')
    expect(result.messages.some((m) => m.level === 'info' && m.message.includes('归一化'))).toBe(true)
  })

  it('should warn when sprites array is empty', () => {
    const result = parseCharacterPack(makeResourcePackage({ sprites: [] }))
    expect(result.ok).toBe(true)
    expect(result.messages.some((m) => m.level === 'warning' && m.field === 'sprites')).toBe(true)
  })

  it('should fail when meta.id is missing', () => {
    const pkg = makeResourcePackage()
    ;(pkg.meta as Record<string, unknown>).id = undefined
    const result = parseCharacterPack(pkg)

    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
    expect(result.messages.some((m) => m.level === 'error' && m.field === 'meta.id')).toBe(true)
  })
})

