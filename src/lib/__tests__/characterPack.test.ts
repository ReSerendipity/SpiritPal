// ============ parseCharacterPack: 通用边界用例 ============

describe('parseCharacterPack: 边界与错误处理', () => {
  it('should fail for null input', () => {
    const result = parseCharacterPack(null)
    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
    expect(result.detectedFormat).toBe('unknown')
  })

  it('should fail for array input', () => {
    const result = parseCharacterPack([1, 2, 3])
    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
  })

  it('should fail for string input', () => {
    const result = parseCharacterPack('hello')
    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
  })

  it('should fail for unrecognized format', () => {
    const result = parseCharacterPack({ foo: 'bar', baz: 123 })
    expect(result.ok).toBe(false)
    expect(result.detectedFormat).toBe('unknown')
    expect(result.messages.some((m) => m.level === 'error' && m.message.includes('无法识别'))).toBe(true)
  })

  it('should warn when spriteAsset is empty', () => {
    const result = parseCharacterPack(makePackConfig({ spritePath: '' }))
    expect(result.ok).toBe(true)
    expect(result.messages.some((m) => m.level === 'warning' && m.field === 'spriteAsset')).toBe(true)
  })

  it('should warn when displayName is empty and use name as fallback', () => {
    const result = parseCharacterPack(makePackConfig({ name: 'fallback-name' }))
    // displayName comes from name in pack-config format
    expect(result.ok).toBe(true)
    expect(result.profile!.displayName).toBe('fallback-name')
  })
})

// ============ parseCharacterPackFromJSON 测试 ============

describe('parseCharacterPackFromJSON', () => {
  it('should parse valid JSON string', () => {
    const json = JSON.stringify(makePackConfig())
    const result = parseCharacterPackFromJSON(json)

    expect(result.ok).toBe(true)
    expect(result.profile!.id).toBe('test-cat')
  })

  it('should fail for invalid JSON string', () => {
    const result = parseCharacterPackFromJSON('{invalid json}')

    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
    expect(result.messages.some((m) => m.level === 'error' && m.message.includes('JSON 解析失败'))).toBe(true)
  })

  it('should fail for empty string', () => {
    const result = parseCharacterPackFromJSON('')

    expect(result.ok).toBe(false)
    expect(result.profile).toBeNull()
  })
})
